/* Earth: continents from the packed map (R land, G signed coast distance, B city lights) + procedural biomes, clouds, ocean glint, atmosphere, night lights. */
(function () {
  var K = window.PGL_SRC.kinds;

  K.earth = { src: [
    'float cloudAt(vec3 p, float oct){',
    '  float ca = u_time*.02;',
    '  vec3 cq = vec3(cos(ca)*p.x - sin(ca)*p.y, sin(ca)*p.x + cos(ca)*p.y, p.z);',
    '  float al = abs(degrees(asin(clamp(p.z,-1.,1.))));',
    '  vec3 wv = vec3(fbm(cq*2.2+1., min(oct,4.)), fbm(cq*2.2+5., min(oct,4.)), fbm(cq*2.2+9., min(oct,4.))) - .5;',
    '  float c1 = fbm(cq*vec3(3.2,3.2,4.8) + wv*1.8, oct);',
    '  float c2 = fbm(cq*vec3(10.,10.,15.) + wv*2.6 + c1*1.4, oct);',
    '  float zon = .07*exp(-pow(al/9.,2.)) - .13*exp(-pow((al-24.)/9.,2.)) + .08*exp(-pow((al-54.)/13.,2.)) + .03*smoothstep(70.,90.,al);',
    '  return smoothstep(.56,.84, c1*.72 + c2*.36 + zon);',
    '}',
    'vec3 surf(vec3 p, vec3 n, vec3 L, vec3 V, float sh){',
    '  float lat = degrees(asin(clamp(p.z,-1.,1.)));',
    '  float al = abs(lat);',
    '  vec2 uv = vec2(atan(p.y,p.x)/(2.*PI) + .5, acos(clamp(p.z,-1.,1.))/PI);',
    '  vec2 uvb = vec2(fract(uv.x + .5) - .5, uv.y);',
    '  vec2 ax1 = dFdx(uv), ay1 = dFdy(uv), ax2 = dFdx(uvb), ay2 = dFdy(uvb);',
    '  vec2 gx = abs(ax1.x) < abs(ax2.x) ? ax1 : ax2;',
    '  vec2 gy = abs(ay1.x) < abs(ay2.x) ? ay1 : ay2;',
    '  vec4 m = textureGrad(u_map, uv, gx, gy);',
    '  float px = 1.4/u_radius;',
    '  float sdw = (m.g - .5)*280.*(2.*PI/2048.);',
    '  float disp = (fbm(p*38., OC(38.)) - .5)*.014 + (fbm(p*140., OC(140.)) - .5)*.0045 + (fbm(p*520., OC(520.)) - .5)*.0016;',
    '  float lnd = smoothstep(-px, px, sdw + disp);',
    // ---- biomes
    '  float nz = fbm(p*7., OC(7.)), nz2 = fbm(p*24., OC(24.)), nz3 = fbm(p*90., OC(90.));',
    '  float wet = fbm(p*2.6 + 4., OC(2.6));',
    '  vec3 pq = normalize(p + .34*(vec3(fbm(p*3.+1., OC(3.)), fbm(p*3.+5., OC(3.)), fbm(p*3.+9., OC(3.))) - .5) + .12*(vec3(nz2, nz, wet) - .5));',
    '  float rain = max(max(blob(pq, ll(-4.,-62.), 15.), blob(pq, ll(0.,23.), 11.)), max(blob(pq, ll(2.,108.), 13.), blob(pq, ll(8.,-77.), 8.)));',
    '  float des = max(max(blob(pq, ll(22.,12.), 22.), blob(pq, ll(24.,45.), 15.)), max(blob(pq, ll(43.,103.), 13.), blob(pq, ll(-25.,134.), 16.)));',
    '  des = max(des, max(max(blob(pq, ll(-23.,21.), 9.), blob(pq, ll(-24.,-69.), 5.)), max(blob(pq, ll(36.,-113.), 8.), blob(pq, ll(30.,60.), 11.))));',
    '  des = max(des, blob(pq, ll(-45.,-69.), 8.)*.6);',
    '  float tropical = 1. - smoothstep(12., 26., al);',
    '  float dband = smoothstep(14.,24.,al)*(1. - smoothstep(32.,42.,al))*smoothstep(.42,.62,1. - wet);',
    '  float dm = clamp(des*(.6 + .8*nz) + dband*.7, 0., 1.);',
    '  vec3 tmp = mix(vec3(.20,.34,.14), vec3(.32,.41,.17), nz);',
    '  vec3 trop = mix(vec3(.06,.22,.08), vec3(.10,.29,.10), nz2);',
    '  vec3 sav = mix(vec3(.44,.43,.20), vec3(.52,.48,.26), nz2);',
    '  vec3 bor = mix(vec3(.09,.21,.13), vec3(.15,.27,.17), nz);',
    '  vec3 tun = mix(vec3(.40,.42,.36), vec3(.52,.50,.44), nz2);',
    '  vec3 dsr = mix(mix(vec3(.58,.49,.35), vec3(.72,.60,.42), nz), vec3(.52,.40,.29), smoothstep(.55,.8,nz2)*.5);',
    '  vec3 land = tmp;',
    '  land = mix(land, mix(sav, trop, smoothstep(.35,.7, rain + wet*.5)), tropical);',
    '  land = mix(land, bor, smoothstep(46.,54.,al));',
    '  land = mix(land, tun, smoothstep(63.,71.,al + 4.*(nz-.5)));',
    '  land = mix(land, dsr, dm);',
    '  float lonD = degrees(atan(p.y,p.x));',
    '  float andes = exp(-pow((lonD + 70. + .35*(lat + 20.))/3.2, 2.))*smoothstep(-56.,-40.,lat)*(1. - smoothstep(-5.,8.,lat));',
    '  float rock = exp(-pow((lonD + 113. + .15*(lat - 40.))/4.5, 2.))*smoothstep(31.,38.,lat)*(1. - smoothstep(58.,66.,lat));',
    '  float mtn = max(max(andes, rock*.8), max(blob(pq, ll(32.,86.), 12.), max(blob(pq, ll(46.,9.), 4.5), blob(pq, ll(42.,48.), 5.5))*.8));',
    '  float rid = 1. - abs(2.*fbm(p*20., OC(20.)) - 1.);',
    '  land = mix(land, vec3(.44,.38,.32)*(.85 + .3*nz3), clamp(mtn*smoothstep(.4,.8,rid)*1.2, 0., 1.));',
    '  float icem = smoothstep(66.,74.,al + 7.*(nz-.5)) + blob(p, ll(72.,-40.), 15.)*smoothstep(.0,.2,1.-wet+.2) + blob(pq, ll(33.,87.), 7.)*smoothstep(.55,.85,rid)*.35;',
    '  land = mix(land, vec3(.94,.96,.99), clamp(icem, 0., 1.));',
    '  land *= .92 + .16*nz3;',
    // ---- ocean
    '  float depth = clamp(-sdw/.07, 0., 1.);',
    '  vec3 oc = mix(vec3(.04,.30,.38), vec3(.012,.05,.16), smoothstep(0.,.75,depth));',
    '  oc *= .88 + .24*fbm(p*30., OC(30.));',
    '  float sice = smoothstep(71.,77., al + 7.*(nz-.5));',
    '  oc = mix(oc, vec3(.90,.94,.98), sice);',
    '  vec3 alb = L2(mix(oc, land, lnd));',
    // ---- clouds
    '  float oct = OC(3.2);',
    '  float cover = cloudAt(p, oct);',
    '  float dl = dot(n,L);',
    '  float cshadow = 0.;',
    '  if(u_radius > 50.){ vec3 tl = L - n*dot(L,n); cshadow = cloudAt(normalize(p - tl*.012), oct); }',
    // ---- light
    '  float E = mix(max(dl,0.), smoothstep(-.08,.55,dl), .55);',
    '  vec3 col = alb*E*1.55*sh*(1. - .5*cshadow);',
    '  vec3 H = normalize(L + V);',
    '  float oceanM = (1. - lnd)*(1. - sice)*(1. - cover);',
    '  float spec = pow(max(dot(n,H),0.), 420.)*1.5 + pow(max(dot(n,H),0.), 60.)*.1;',
    '  col += L2(vec3(1.,.95,.85))*spec*oceanM*smoothstep(0.,.2,dl);',
    '  float mu = max(dot(n,V), 0.);',
    '  col += L2(vec3(.35,.55,.9))*pow(1. - mu, 5.)*.5*E*(1. - lnd)*(1. - cover);',
    '  vec3 cc = mix(vec3(.80,.85,.93), vec3(1.), smoothstep(.2,.95,cover));',
    '  vec3 ccol = L2(cc)*(E*1.7 + .004);',
    '  col = mix(col, ccol, pow(cover, 1.3)*.9);',
    // ---- atmosphere
    '  float at = pow(1. - mu, 2.4);',
    '  col += L2(vec3(.28,.52,1.))*at*.8*smoothstep(-.12,.5,dl);',
    '  float tw = exp(-pow((dl - .03)/.12, 2.));',
    '  col *= mix(vec3(1.), vec3(1.,.74,.56), tw*.32*smoothstep(-.05,.08,dl));',
    '  col += L2(vec3(1.,.5,.2))*tw*at*.2*smoothstep(-.09,.02,dl);',
    // ---- night side
    '  if(u_night > .5){',
    '    float nf = smoothstep(.04, -.18, dl);',
    '    float lights = m.b*lnd*nf*(1. - cover*.8);',
    '    lights *= .55 + .9*fbm(p*300., OC(300.));',
    '    col += L2(vec3(1.,.74,.40))*lights*2.4;',
    '    col += alb*.0045*(1. - cover*.4) + L2(vec3(.2,.3,.5))*cover*.004;',
    '  } else col += alb*.05;',
    '  return col;',
    '}',
    ''
  ].join('\n') };
})();
